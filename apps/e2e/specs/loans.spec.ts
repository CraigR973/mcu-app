import { filmId } from '../support/films.ts'
import { registerDevice, pushesTo } from '../support/push.ts'
import { expect, test } from '../support/test.ts'

test('a requested copy is taken, returned and put back on a confirmed or changed shelf', async ({ signedIn, api }, testInfo) => {
  const craig = await api('Craig')
  const mark = await api('Mark')
  const device = await registerDevice(mark, 'aa11-Mark')
  await mark.put('/notifications/preferences', { loansEnabled: true, clearQuietHours: true, digestMode: false })
  const movie = await filmId(craig, 'The Quiet Engine')
  const { page } = await signedIn('Craig')
  await page.setViewportSize({ width: 375, height: 812 })
  await page.goto(`/movies/${movie}`)
  await page.getByRole('button', { name: 'Ask to borrow', exact: true }).first().click()
  const form = page.getByRole('form', { name: 'Ask to borrow this disc' })
  const needed = new Date(Date.now() + 3 * 86400000).toISOString().slice(0, 10)
  await form.getByLabel('Needed by').fill(needed)
  await form.getByRole('button', { name: 'Send request' }).click()
  await expect(page.getByText('Asked for', { exact: true }).first()).toBeVisible()
  await expect.poll(() => pushesTo(device).filter((push) => push.title?.includes('asked for The Quiet Engine')).length).toBe(1)
  expect(pushesTo(device).find((push) => push.title?.includes('asked for The Quiet Engine'))?.url).toBe('/loans')
  const loans = await craig.get<{ items: { id: string; movieId: string; state: string; lentDate: string | null; neededBy: string; isCurrent: boolean }[] }>('/loans')
  const requested = loans.items.find((loan) => loan.movieId === movie && loan.state === 'asked_for' && loan.isCurrent)
  expect(requested?.lentDate).toBeNull()
  expect(requested?.neededBy).toBe(needed)
  await page.screenshot({ path: testInfo.outputPath('aa11-requested-375px.png'), fullPage: true })
  const { page: markPage } = await signedIn('Mark')
  await markPage.setViewportSize({ width: 375, height: 812 })
  await markPage.goto('/loans')
  let row = markPage.getByRole('listitem').filter({ hasText: 'The Quiet Engine' }).filter({ hasText: 'Asked for' })
  await row.getByRole('button', { name: 'Taken', exact: true }).click()
  await expect(row).toHaveCount(0)
  row = markPage.getByRole('listitem').filter({ hasText: 'The Quiet Engine' }).filter({ hasText: 'Out' })
  await expect(row).toBeVisible()
  await page.goto('/loans')
  await page.getByRole('listitem').filter({ hasText: 'The Quiet Engine' }).getByRole('button', { name: 'Returned', exact: true }).click()
  await page.getByRole('button', { name: 'To put back', exact: true }).click()
  await expect(page.getByText('Back, not shelved', { exact: true })).toBeVisible()
  await markPage.reload()
  await markPage.getByRole('button', { name: 'To put back', exact: true }).click()
  await markPage.getByRole('button', { name: 'Put back', exact: true }).click()
  await markPage.getByLabel('Change shelf').check()
  await markPage.getByLabel('Section', { exact: true }).selectOption('Back')
  await markPage.getByLabel('Shelf or side (optional)').fill('3rd')
  await markPage.screenshot({ path: testInfo.outputPath('aa11-put-back-375px.png'), fullPage: true })
  await markPage.getByRole('button', { name: 'Confirm shelved', exact: true }).click()
  await expect(markPage.getByText('Nothing to put back')).toBeVisible()
  await markPage.getByRole('button', { name: 'All', exact: true }).click()
  await expect(markPage.getByRole('listitem').filter({ hasText: 'The Quiet Engine' })).toContainText('Shelved')
  await page.goto(`/movies/${movie}`)
  await expect(page.getByText('Shelved', { exact: true }).first()).toBeVisible()
  await expect(page.getByText('Home position: Back 3rd', { exact: true }).first()).toBeVisible()
  await expect(page.getByRole('button', { name: 'Borrow', exact: true }).first()).toBeVisible()
})
